#!/usr/bin/env node
'use strict';

/**
 * Writes src/sw-version.ts from NEXT_PUBLIC_APP_VERSION (or the package
 * version) so the service worker can namespace and expire its caches by
 * release. Runs before `dev`/`build`; the output is git-ignored.
 */

const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');
const version = process.env.NEXT_PUBLIC_APP_VERSION || pkg.version || '0.1.0';

const content = `// Auto-generated by scripts/generate-sw-version.js — do not edit
export const APP_VERSION = '${version}';
`;

const outPath = path.join(__dirname, '..', 'src', 'sw-version.ts');
fs.writeFileSync(outPath, content, 'utf8');
console.log(`[SW] Version file generated: ${version}`);
